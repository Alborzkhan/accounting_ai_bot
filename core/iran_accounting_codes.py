def get_codes_for_business(business_type: str) -> Dict:
    """دریافت کدینگ مناسب برای نوع کسب‌وکار."""
    codes = dict(GENERAL_CODES)
    biz_codes = BUSINESS_TYPE_CODES.get(business_type, BUSINESS_TYPE_CODES.get("بازرگانی", {}))
    codes.update(biz_codes)
    return codes


def get_account_name(code: str, business_type: str = "بازرگانی") -> str:
    """دریافت نام حساب بر اساس کد و نوع کسب‌وکار."""
    codes = get_codes_for_business(business_type)
    return codes.get(code, {}).get("name", "نامشخص")


def get_account_type(code: str, business_type: str = "بازرگانی") -> str:
    """دریافت نوع حساب بر اساس کد."""
    codes = get_codes_for_business(business_type)
    return codes.get(code, {}).get("type", "unknown")


def get_income_codes(business_type: str = "بازرگانی") -> Dict[str, str]:
    """دریافت کدهای درآمدی مناسب برای نوع کسب‌وکار."""
    codes = get_codes_for_business(business_type)
    return {k: v["name"] for k, v in codes.items() if v["type"] == "income"}


def get_expense_codes(business_type: str = "بازرگانی") -> Dict[str, str]:
    """دریافت کدهای هزینه‌ای مناسب برای نوع کسب‌وکار."""
    codes = get_codes_for_business(business_type)
    return {k: v["name"] for k, v in codes.items() if v["type"] == "expense"}



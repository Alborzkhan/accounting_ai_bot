def suggest_accounts(description: str, business_type: str = "بازرگانی") -> Tuple[str, str]:
    """پیشنهاد حساب بدهکار و بستانکار بر اساس شرح و نوع کسب‌وکار."""
    debit = "1201"
    credit = "2001"

    for code, keywords in KEYWORD_MAPPING.items():
        for kw in keywords:
            if kw in description:
                codes = get_codes_for_business(business_type)
                if code in codes:
                    info = codes[code]
                    if info.get("type") in ("income", "liability", "equity"):
                        credit = code
                    elif info.get("type") in ("expense", "asset"):
                        debit = code
                break

    return debit, credit


